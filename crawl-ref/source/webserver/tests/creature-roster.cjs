const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
let model;
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../game_data/static/creature-roster-model.js'), 'utf8'),
    { define(deps, factory) { model = factory(); } });
for (const att of [1, 2, 3]) assert.equal(model.category({ att }), 'neutrals');
assert.equal(model.category({ att: 4, non_threatening: true }), 'allies');
assert.equal(model.category({ att: 0, non_threatening: true }), 'neutrals');
assert.equal(model.category({ att: 0 }), 'enemies');
assert.equal(model.category({ speed: 0 }), 'enemies', 'Immobility alone cannot turn a dangerous statue neutral');
const plant = { id: 90, contact_key: 'map:90', name: 'plant', type: 5, x: 2, y: 3, att: 0, non_threatening: true, perception: 'visible' };
const reading = { id: 8, name: 'plant', x: 2, y: 3, speed: 0, energy_deficit: 10, damage_level: 0, statuses_known: true, statuses: [], perception: 'visible' };
let merged = model.collect([reading], [plant]);
assert.equal(merged.length, 1);
assert.equal(model.key(merged[0]), '8', 'Map client IDs and native monster IDs use separate namespaces');
assert.equal(model.category(merged[0]), 'neutrals');
assert.equal(merged[0].speed, 0);
merged = model.collect([{ ...reading, perception: 'last_known' }], [plant]);
assert.equal(merged.length, 2);
assert.equal(model.category(merged[0]), 'enemies', 'Invisible memories do not borrow visible attitudes');
assert.equal(merged[0].non_threatening, undefined);
merged = model.collect([{ ...reading, name: 'statue' }], [plant]);
assert.equal(merged.length, 2, 'Asynchronous map and initiative frames cannot merge different actors');
const contacts = Array.from({ length: 500 }, (_, i) => ({ ...reading, id: i + 1, x: i }));
let groups = model.groups(contacts);
assert.equal(groups[0].count, 500);
assert.equal(groups[0].stacks.size, 1, 'Identical cards share a stack');
contacts[1].damage_level = 3;
contacts[2].statuses = [{ text: 'poisoned', is_bad: true }];
contacts[3].energy_deficit = 2;
contacts[4].att = 4;
contacts[5].att = 1;
groups = model.groups(contacts);
assert.equal(groups[0].stacks.size, 4, 'Distinct injury, effects and readiness remain individually visible');
assert.equal(groups[0].count, 498);
assert.equal(groups[1].count, 1);
assert.equal(groups[2].count, 1);
assert.equal(groups[2].open, false);
console.log('Creature categories, map/native identity, invisible privacy and 500-contact stacking passed.');
