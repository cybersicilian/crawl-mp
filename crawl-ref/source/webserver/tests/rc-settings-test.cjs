/* Real menu, client protocol and isolated backend persistence. No native game. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { once } = require('node:events');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '../../../..');
const output = process.env.SETTINGS_PROOF_DIR || path.join(root, 'docs/game-settings-2026-10-28');
fs.mkdirSync(output, { recursive: true });
const portFile = path.join(output, 'fixture-port.txt');
fs.rmSync(portFile, { force: true });
const server = spawn(process.env.DCSS_PYTHON || path.join(root, '.venv/bin/python'),
    [path.join(__dirname, 'helpers/game-settings-fixture.py'), '--port-file', portFile],
    { cwd: root, env: { ...process.env, PYTHONPATH: path.join(root, 'crawl-ref/source/webserver') }, stdio: ['ignore', 'pipe', 'pipe'] });
let serverLog = '', browser;
server.stderr.on('data', data => { serverLog += data; });
const closed = once(server, 'exit');
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
    for (let i = 0; !fs.existsSync(portFile) && i < 100; i++) {
        if (server.exitCode !== null) throw new Error(serverLog);
        await delay(50);
    }
    assert(fs.existsSync(portFile), 'Fixture starts');
    const url = 'http://127.0.0.1:' + fs.readFileSync(portFile, 'utf8');
    browser = await chromium.launch({ headless: true, channel: 'chrome' });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(url);
    await page.waitForFunction(() => window.ready && document.querySelectorAll('.rc-setting').length === 132);
    const search = page.getByRole('searchbox', { name: 'Find a setting' });
    const travel = page.locator('#rc_setting_travel_delay');
    const weaponSwap = page.locator('#rc_setting_autofight_weapon_swap');
    const save = page.getByRole('button', { name: 'Save settings', exact: true });
    const resetTravel = page.getByRole('button', { name: 'Reset Travel speed to base default', exact: true });
    const selectTravel = async () => { await search.fill(''); await page.getByRole('button', { name: 'Travel & rest', exact: true }).click(); };
    const saved = async () => { await page.waitForFunction(() => document.getElementById('rc_settings_status').textContent.startsWith('Settings saved.')); };
    assert.equal(await travel.inputValue(), '75');
    assert.match(await travel.locator('..').textContent(), /Base default: 20/);
    assert.equal(await page.locator('#rc_setting_explore_delay').inputValue(), '0');
    assert.equal(await weaponSwap.inputValue(), 'false', 'Weapon swapping is opt-in');
    assert.equal(await page.locator('#rc_file_contents, #rc_advanced').count(), 0);
    assert.equal(await page.locator('#rc_settings_categories button').count(), 8);
    await page.screenshot({ path: path.join(output, 'settings-desktop.png') });
    await resetTravel.click(); assert.equal(await travel.inputValue(), '20');
    await page.getByRole('button', { name: 'Undo changes', exact: true }).click();
    assert.equal(await travel.inputValue(), '75');
    await page.getByRole('button', { name: 'Combat & casting', exact: true }).click();
    await weaponSwap.selectOption('true');
    await selectTravel();
    await travel.fill('31'); await save.click();
    assert(await page.getByRole('button', { name: 'Cancel', exact: true }).isDisabled());
    await saved(); assert(await page.getByRole('button', { name: 'Close', exact: true }).isEnabled());
    await page.evaluate(() => window.app.edit_rc('solo'));
    await page.locator('#rc_settings_workspace').waitFor({ state: 'visible' });
    await page.waitForFunction(() => document.getElementById('rc_setting_travel_delay').value === '31');
    assert.equal(await weaponSwap.inputValue(), 'true', 'Weapon swapping survives save and reopen');
    await page.getByRole('button', { name: 'Use existing configuration for Travel speed', exact: true }).click();
    assert.equal(await travel.inputValue(), '75'); await save.click(); await saved();
    await search.fill('low-health');
    assert.equal(await page.locator('.rc-setting:visible').count(), 2);
    await page.locator('#rc_setting_hp_warning').fill('41'); await save.click(); await saved();
    await search.fill('Auto-pickup rules');
    const rules = page.locator('#rc_setting_autopickup_exceptions');
    await rules.fill('<potion of curing\n>scroll of noise\n');
    assert.equal(await rules.inputValue(), '<potion of curing\n>scroll of noise\n', 'Input retains trailing line for continued typing');
    await save.click(); await saved();
    await selectTravel(); await travel.fill('33');
    await page.evaluate(() => require('comm').send_message('fixture_fail_next', {}));
    await save.click(); await page.locator('#rc_settings_error').waitFor({ state: 'visible' });
    assert.equal(await travel.inputValue(), '33'); assert(await save.isEnabled());
    await save.click(); await saved();
    await travel.fill('34'); await travel.fill('-2');
    const before = await page.evaluate(() => window.sent.length);
    await page.getByRole('button', { name: 'Items & inventory', exact: true }).click();
    await save.click(); await delay(150);
    assert(await travel.isVisible(), 'Validation reveals a hidden invalid field');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'rc_setting_travel_delay');
    assert.equal(await page.evaluate(() => window.sent.length), before, 'Invalid values never reach the server');
    await page.getByRole('button', { name: 'Undo changes', exact: true }).click();
    await page.evaluate(() => window.app.game_settings({ game_id:'solo', request_id:'stale', username:'Aster', available:false,error:'stale response' }));
    assert.equal(await page.locator('#rc_settings_error').isVisible(), false);
    const state = await (await page.request.get(url + '/state')).json();
    assert.equal(state.original, '# Existing custom settings\ntravel_delay = 75\ndefault_autopickup = false\nunknown_extension = retained\n');
    assert.equal(state.save, 'A save this fixture must not touch.');
    assert(state.arguments.includes('travel_delay = 33')); assert(state.arguments.includes('hp_warning = 41'));
    assert(state.arguments.includes('autofight_weapon_swap = true'));
    assert(state.arguments.includes('autopickup_exceptions = <potion of curing, >scroll of noise'));
    await page.getByLabel('Customized only', { exact: true }).check();
    await page.getByRole('button', { name: 'All settings', exact: true }).click();
    assert(await page.locator('.rc-setting:visible').count() < 132);
    await page.getByLabel('Customized only', { exact: true }).uncheck(); await selectTravel();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const layout = await page.evaluate(() => {
        const r = document.getElementById('rc_edit').getBoundingClientRect();
        return { viewport: innerWidth, pageWidth: document.documentElement.scrollWidth, dialog: {left:r.left,right:r.right,width:r.width} };
    });
    fs.writeFileSync(path.join(output, 'layout.json'), JSON.stringify(layout, null, 2));
    await page.screenshot({ path: path.join(output, 'settings-mobile.png') });
    assert(layout.pageWidth <= layout.viewport, JSON.stringify(layout));
    await page.screenshot({ path: path.join(output, 'settings-mobile.png') });
    await page.getByRole('button', { name: 'Close', exact: true }).focus(); await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'rc_settings_search', 'Tab wraps inside the modal');
    await page.keyboard.press('Escape'); assert.equal(await page.locator('#rc_edit').isVisible(), false);
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output, 'browser-result.json'), JSON.stringify({ passed:true, settings:132,
        screenshots:['settings-desktop.png','settings-mobile.png'], nativeGameStarted:false,
        rcPreserved:true, savePreserved:true, runtimeArguments:state.arguments, browserErrors:errors }, null, 2));
    console.log('Settings browser checks passed: defaults, edits, resets, search, persistence, failures, validation, responsive layout and keyboard controls.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
    if (browser) await browser.close();
    server.kill('SIGTERM'); await closed;
    fs.rmSync(portFile, { force: true });
});
