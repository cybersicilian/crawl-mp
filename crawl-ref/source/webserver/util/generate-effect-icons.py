#!/usr/bin/env python3
"""Pack reviewed native artwork; fail if effect coverage or source pixels drift."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re

from PIL import Image
from effect_catalog import ROOT, catalogue

WEB = ROOT / 'webserver'
ART = ROOT / 'rltiles'
SIZE, COLUMNS = 32, 16


def sha(data):
    return hashlib.sha256(data).hexdigest()


def compact_json(value):
    return json.dumps(value, ensure_ascii=True, separators=(',', ':'))


def native_keys(file, prefix):
    """Carry enum preprocessor guards through to native symbolic key switches."""
    lines = []
    for line in (ROOT / file).read_text().splitlines():
        if line.startswith(('#if ', '#else', '#endif')):
            lines.append(line)
        match = re.match(r'\s*(' + prefix + r'[A-Z_0-9]+)\b', line)
        if match and not match[1].endswith('LAST_STATUS'):
            lines.append(f'    case {match[1]}: return "{match[1]}";')
    return lines


def header(function, includes, lines):
    return '\n'.join(['// Generated by webserver/util/generate-effect-icons.py; do not edit.',
        '#pragma once', *[f'#include "{name}"' for name in includes], '',
        f'inline const char* {function}(int id)', '{', '    switch (id)', '    {',
        *lines, '    default: return "";', '    }', '}', ''])


def outputs():
    definitions = catalogue()
    mapping = json.loads(Path(__file__).with_name('effect-art-map.json').read_text())
    recipes = {row['key']: row for row in mapping}
    if len(recipes) != len(mapping) or set(recipes) != {row['key'] for row in definitions}:
        raise ValueError('Every native effect needs exactly one reviewed art recipe')
    subjects = list(dict.fromkeys(row['source'] for row in mapping))
    atlas = Image.new('RGBA', (SIZE * COLUMNS, SIZE * ((len(subjects) + COLUMNS - 1) // COLUMNS)))
    frames, sources = {}, {}
    for index, source in enumerate(subjects):
        path = (ART / source).resolve()
        if not path.is_relative_to(ART) or not path.is_file():
            raise ValueError('Missing or invalid native artwork: ' + source)
        with Image.open(path) as original:
            image = original.convert('RGBA')
        bounds = image.getbbox()
        if not bounds:
            raise ValueError('Empty artwork: ' + source)
        # Normalize transparent padding, especially tiny native map overlays.
        image = image.crop(bounds)
        scale = min(3, max(1, min(28 // image.width, 28 // image.height)))
        if image.width > 32 or image.height > 32:
            raise ValueError('Oversized native artwork: ' + source)
        image = image.resize((image.width * scale, image.height * scale), Image.Resampling.NEAREST)
        x, y = (index % COLUMNS) * SIZE, (index // COLUMNS) * SIZE
        atlas.paste(image, (x + (SIZE - image.width) // 2, y + (SIZE - image.height) // 2))
        frames[source] = index
        sources[source] = {'sha256': sha(path.read_bytes()), 'bounds': bounds, 'scale': scale}
    buffer = io.BytesIO()
    atlas.save(buffer, format='PNG', optimize=True)
    raw = buffer.getvalue()
    filename = 'effects.' + sha(raw)[:12] + '.png'
    metadata = {'url': '/static/effect-icons/' + filename, 'size': SIZE,
        'columns': COLUMNS, 'width': atlas.width, 'height': atlas.height}
    records = []
    for row in definitions:
        recipe = recipes[row['key']]
        aliases = list(dict.fromkeys([row['name'], *row['aliases']]))
        records.append([row['key'], frames[recipe['source']], aliases, recipe['modifier']])
    javascript = '\n'.join(['// Generated from native identities and reviewed artwork; do not edit.',
        'define([], function () {', '    "use strict";',
        '    return { atlas: ' + compact_json(metadata) + ', entries: [',
        *['        ' + compact_json(row) + (',' if i < len(records) - 1 else '') for i, row in enumerate(records)],
        '    ] };', '});', ''])
    manifest = '\n'.join(['{', '  "atlas": ' + compact_json(metadata) + ',',
        '  "effects": ' + str(len(records)) + ',', '  "sources": {',
        *['    ' + json.dumps(source) + ': ' + compact_json(sources[source])
          + (',' if i < len(subjects) - 1 else '') for i, source in enumerate(subjects)], '  }', '}', ''])
    monster_lines = []
    text = (ROOT / 'mon-info-flag-name.h').read_text()
    for line in text.splitlines():
        if line.startswith(('#if ', '#else', '#endif')):
            monster_lines.append(line)
        match = re.match(r'\s*\{\s*(MB_[A-Z_0-9]+),', line)
        if match:
            monster_lines.append(f'    case {match[1]}: return "{match[1]}";')
    monster_lines += ['    case NUM_MB_FLAGS: return "MON_AIM_IMPAIRED";',
                      '    case NUM_MB_FLAGS + 1: return "MON_MEMORIES";']
    return {WEB / 'static/effect-icons' / filename: raw,
        WEB / 'static/effect-icons/manifest.json': manifest.encode(),
        WEB / 'game_data/static/effect-icon-catalog.js': javascript.encode(),
        ROOT / 'web-effect-keys.h': header('web_effect_key', ['status.h'],
            native_keys('duration-type.h', 'DUR_') + native_keys('status.h', 'STATUS_')).encode(),
        ROOT / 'web-bane-keys.h': header('web_bane_key', ['bane-type.h'], native_keys('bane-type.h', 'BANE_')).encode(),
        ROOT / 'web-monster-effect-keys.h': header('web_monster_effect_key', ['mon-info.h'], monster_lines).encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    files = outputs()
    for path, data in files.items():
        if args.verify:
            if not path.is_file() or path.read_bytes() != data:
                raise ValueError('Generated output differs: ' + str(path))
        else:
            path.parent.mkdir(exist_ok=True, parents=True)
            path.write_bytes(data)
    print(json.dumps({'verified' if args.verify else 'built': True, 'effects': len(catalogue()), 'outputs': len(files)}))


if __name__ == '__main__':
    main()
